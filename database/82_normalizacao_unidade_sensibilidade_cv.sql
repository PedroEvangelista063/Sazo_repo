-- ============================================================================
-- MIGRATION 82 — Refinamento Estatístico, Normalização de Grandezas e
--                Data Healing (Semáforo Sensível por Coeficiente de Variação)
-- ============================================================================
-- Contexto: a fact é poluída por preços de grandezas diferentes (PITAYA que
-- varia de R$ 0,01 a R$ 108 dependendo da unidade da coleta — caixa, kg,
-- unidade). O semáforo clássico ±desvio vira VERMELHO/VERDE espúrio.
--
-- Decisão (definitiva):
--   1) GRANULARIDADE NA FACT: staging.fact_precos_mensais passa a carregar
--      unidade_canonica + fator_kg + fluxo_unidade; o UNIQUE vira
--      (id_produto, id_localidade, ano, mes, COALESCE(unidade_canonica,'kg')).
--   2) SAZONALIDADE ESCOLHE KG: mart.sazonalidade_produto mantém o UNIQUE
--      atual (1 linha/mês) e a SP escolhe a linha por DISTINCT ON com
--      prioridade kg > fator_kg conhecido > genérico.
--   3) Semáforo passa a usar a BANDA PROPORCIONAL ao coeficiente de variação
--      (CV) da série de 24 meses, com piso de faixa por magnitude de preço.
--
-- Fases:
--   Fase 1 (pipeline/etl_conab_diario.py) — transform per-unidade (feita).
--   Fase 2 — DDL: mart.dim_unidade_medida + seeds + ALTER fact + normalizador SQL.
--   Fase 3 — Motor matemático CV: estatisticas_volatilidade_24m_cv() +
--            calcular_semaforo_preco_sensivel() (+ retrocompat 3-arg).
--   Fase 4 — Backfill da unidade na fact (ANTES da mudança de UNIQUE).
--   Fase 5 — Procedure central sp_calcular_sazonalidade (kg-first + CV).
--   Fase 6 — Validation Gate: ops.simulacao_semaforo_v82.
--   Rollback — instruções comentadas no fim.
--
-- Execução: 1x, na ordem do arquivo (idempotente). NÃO sobrescreve
-- unidade_canonica já preenchida na fact.

-- ============================================================================
