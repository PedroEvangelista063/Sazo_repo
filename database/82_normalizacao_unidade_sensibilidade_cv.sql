-- ---------------------------------------------------------------------------
-- 2.3 — staging.normalizar_unidade_sql(p_unidade) — espelho SQL do Python
-- ---------------------------------------------------------------------------
-- Espelho da função Python normalizar_unidade_sig() do ETL diário:
--  1. match direto por sinonimo/canonico na dim (normaliza espelhos)
--  2. regex "N kg" → kg com fator N
--  3. fallback: unidade crua lowercase, fator NULL, nao confiavel.

CREATE OR REPLACE FUNCTION staging.normalizar_unidade_sql(p_unidade TEXT)
RETURNS TABLE (unidade_canonica TEXT, fator_kg NUMERIC, eh_confiavel BOOLEAN)
LANGUAGE sql
STABLE
AS $$
    WITH sig AS (
        SELECT LOWER(BTRIM(COALESCE(p_unidade, ''))) AS s
    ),
    direto AS (
        SELECT um.unidade_canonica, um.fator_kg, um.eh_confiavel
        FROM mart.dim_unidade_medida um, sig
        WHERE sig.s = um.unidade_canonica
           OR sig.s = ANY(um.sinonimos)
        LIMIT 1
    ),
    regex_kg AS (
        SELECT 'kg'::TEXT AS unidade_canonica,
               (REGEXP_MATCH(sig.s, '^(\d+)\s*kg\b'))[1]::NUMERIC AS fator_kg,
               TRUE AS eh_confiavel
        FROM sig
        WHERE sig.s ~ '^(\d+)\s*kg\b'
    )
    SELECT
        COALESCE(d.unidade_canonica, r.unidade_canonica, s.s) AS unidade_canonica,
        COALESCE(d.fator_kg, r.fator_kg)                       AS fator_kg,
        COALESCE(d.eh_confiavel, r.eh_confiavel, FALSE)        AS eh_confiavel
    FROM sig s
    LEFT JOIN direto d ON TRUE
    LEFT JOIN regex_kg r ON TRUE;
$$;

COMMENT ON FUNCTION staging.normalizar_unidade_sql(TEXT) IS
    'Espelho SQL do normalizador Python do ETL diário CONAB. Prioridade: '
    '(1) match direto na dim_unidade_medida por sinonimo/canonico; '
    '(2) regex "^N kg" → kg com fator N; (3) fallback: unidade crua '
    'lowercase com fator NULL. Uso: SELECT * FROM staging.normalizar_unidade_sql(''cx 20kg'');';

GRANT EXECUTE ON FUNCTION staging.normalizar_unidade_sql(TEXT) TO role_etl_writer;
GRANT SELECT ON mart.dim_unidade_medida TO role_api_reader, role_etl_writer;

