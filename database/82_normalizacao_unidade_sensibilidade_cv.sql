-- ---------------------------------------------------------------------------
-- Reescrita da SP: escolhe a linha kg-first ANTES da média móvel e usa o
-- semáforo sensível por CV.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE staging.sp_calcular_sazonalidade(IN p_ano_alvo smallint DEFAULT NULL::smallint, IN p_mes_alvo smallint DEFAULT NULL::smallint)
 LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_ano    SMALLINT;
    v_mes    SMALLINT;
    v_inicio TIMESTAMPTZ;
    v_fim    TIMESTAMPTZ;
    v_total  INTEGER;
BEGIN
    v_inicio := clock_timestamp();

    IF p_ano_alvo IS NULL OR p_mes_alvo IS NULL THEN
        SELECT MAX(ano), MAX(mes) INTO v_ano, v_mes
        FROM staging.fact_precos_mensais;
    ELSE
        v_ano := p_ano_alvo;
        v_mes := p_mes_alvo;
    END IF;

    RAISE NOTICE '[sp_calcular_sazonalidade] Alvo: %-% (regra CV v82)', v_ano, v_mes;

    INSERT INTO mart.sazonalidade_produto (
        id_produto, id_localidade, ano, mes,
        preco_medio, media_movel_12m, indice_sazonalidade,
        status_cor, fonte, calculado_em,
        preco_atual, preco_referencia,
        desvio_padrao_historico, limite_superior, limite_inferior,
        preco_mes_anterior, variacao_mom_pct,
        data_referencia_atual,
        cv_serie, contam_unidade, metadado_transparencia
    )
    WITH fact_kg AS (
        -- Escolhe UMA linha por (produto, localidade, ano, mes) com prioridade
        -- kg > fator_kg conhecido > genérico. A média móvel e o índice
        -- sazonal são calculados sobre a série JÁ escolhida.
        SELECT DISTINCT ON (f.id_produto, f.id_localidade, f.ano, f.mes)
            f.id_produto,
            f.id_localidade,
            f.ano,
            f.mes,
            f.preco_medio,
            f.unidade_canonica,
            f.fator_kg
        FROM staging.fact_precos_mensais f
        WHERE (f.ano < v_ano OR (f.ano = v_ano AND f.mes <= v_mes))
          AND f.preco_medio IS NOT NULL
        ORDER BY
            f.id_produto,
            f.id_localidade,
            f.ano,
            f.mes,
            CASE
                WHEN f.unidade_canonica = 'kg' THEN 0
                WHEN f.fator_kg IS NOT NULL THEN 1
                ELSE 2
            END,
            f.unidade_canonica
    ),
    precos_12m AS (
        SELECT
            f.id_produto,
            f.id_localidade,
            f.ano,
            f.mes,
            f.preco_medio,
            AVG(f.preco_medio) OVER (
                PARTITION BY f.id_produto, f.id_localidade
                ORDER BY f.ano, f.mes
                ROWS BETWEEN 11 PRECEDING AND CURRENT ROW
            ) AS media_movel_12m,
            COUNT(*) OVER (
                PARTITION BY f.id_produto, f.id_localidade
                ORDER BY f.ano, f.mes
                ROWS BETWEEN 11 PRECEDING AND CURRENT ROW
            ) AS meses_no_window,
            LAG(f.preco_medio) OVER (
                PARTITION BY f.id_produto, f.id_localidade
                ORDER BY f.ano, f.mes
            ) AS preco_mes_anterior
        FROM fact_kg f
    ),
    volatilidade AS MATERIALIZED (
        SELECT * FROM staging.estatisticas_volatilidade_24m_cv()
    )
    SELECT
        p.id_produto,
        p.id_localidade,
        p.ano,
        p.mes,
        p.preco_medio,
        p.media_movel_12m,
        CASE
            WHEN p.media_movel_12m IS NOT NULL AND p.media_movel_12m > 0
            THEN ROUND(p.preco_medio / p.media_movel_12m, 4)
            ELSE NULL
        END AS indice_sazonalidade,
        CASE
            WHEN p.meses_no_window < 6 THEN 'AMARELO'
            WHEN v.contam_unidade THEN 'AMARELO'
            WHEN v.desvio_efetivo IS NULL THEN 'AMARELO'
            ELSE COALESCE(
                staging.calcular_semaforo_preco_sensivel(
                    p.preco_medio, p.media_movel_12m, v.cv_serie, 1
                ),
                'AMARELO'
            )
        END AS status_cor,
        'municipio' AS fonte,
        NOW() AS calculado_em,
        p.preco_medio AS preco_atual,
        p.preco_medio AS preco_referencia,
        v.desvio_efetivo AS desvio_padrao_historico,
        p.media_movel_12m + v.desvio_efetivo AS limite_superior,
        p.media_movel_12m - v.desvio_efetivo AS limite_inferior,
        p.preco_mes_anterior,
        CASE
            WHEN p.preco_mes_anterior IS NULL OR p.preco_mes_anterior <= 0
                 OR p.preco_medio IS NULL OR p.preco_medio <= 0
            THEN NULL
            ELSE ROUND(((p.preco_medio / p.preco_mes_anterior) - 1) * 100, 4)
        END AS variacao_mom_pct,
        p.ano::TEXT || '-' || LPAD(p.mes::TEXT, 2, '0') AS data_referencia_atual,
        v.cv_serie,
        v.contam_unidade,
        CASE
            WHEN v.contam_unidade THEN
                jsonb_build_object(
                    'regra', 'cv_sensivel_v82',
                    'contam_unidade', v.contam_unidade,
                    'aviso', 'serie temporal com mistura de grandezas -> baixa confiabilidade estatistica'
                )
            ELSE NULL
        END AS metadado_transparencia
    FROM precos_12m p
    LEFT JOIN LATERAL (
        SELECT st.cv_serie, st.contam_unidade, st.desvio_efetivo
        FROM volatilidade st
        WHERE st.id_produto = p.id_produto
          AND st.id_localidade = p.id_localidade
    ) v ON TRUE
    WHERE p.ano = v_ano AND p.mes = v_mes
    ON CONFLICT (id_produto, id_localidade, ano, mes)
    DO UPDATE SET
        preco_medio         = EXCLUDED.preco_medio,
        media_movel_12m     = EXCLUDED.media_movel_12m,
        indice_sazonalidade = EXCLUDED.indice_sazonalidade,
        status_cor          = EXCLUDED.status_cor,
        fonte               = EXCLUDED.fonte,
        calculado_em        = NOW(),
        preco_atual         = EXCLUDED.preco_atual,
        preco_referencia    = EXCLUDED.preco_referencia,
        desvio_padrao_historico = EXCLUDED.desvio_padrao_historico,
        limite_superior     = EXCLUDED.limite_superior,
        limite_inferior     = EXCLUDED.limite_inferior,
        preco_mes_anterior  = EXCLUDED.preco_mes_anterior,
        variacao_mom_pct    = EXCLUDED.variacao_mom_pct,
        data_referencia_atual = EXCLUDED.data_referencia_atual,
        cv_serie            = EXCLUDED.cv_serie,
        contam_unidade      = EXCLUDED.contam_unidade,
        metadado_transparencia = CASE
            WHEN EXCLUDED.contam_unidade THEN EXCLUDED.metadado_transparencia
            ELSE mart.sazonalidade_produto.metadado_transparencia
        END;

    GET DIAGNOSTICS v_total = ROW_COUNT;
    v_fim := clock_timestamp();

    RAISE NOTICE '[sp_calcular_sazonalidade] Concluído: % linhas em % seg',
        v_total, ROUND(EXTRACT(EPOCH FROM v_fim - v_inicio)::NUMERIC, 2);
END;
$procedure$;

-- ============================================================================
-- FASE 6 — Validation Gate: ops.simulacao_semaforo_v82
-- ============================================================================
-- View de auditoria: compara o status_cor ATUAL (regra antiga) com o
-- status_cor que a regra sensível por CV produziria, expõe cv_real,
-- contam_unidade, unidade_inferida e metadado_transparencia. Prioriza
-- maiores |preco_atual - preco_referencia| e produtos PITAYA/BATATA/ALFACE.
-- LIMIT 1000 — as linhas mais críticas.

CREATE OR REPLACE VIEW ops.simulacao_semaforo_v82 AS
WITH volatilidade AS MATERIALIZED (
    SELECT * FROM staging.estatisticas_volatilidade_24m_cv()
),
unidade_fact AS (
    SELECT DISTINCT ON (f.id_produto, f.id_localidade, f.ano, f.mes)
        f.id_produto,
        f.id_localidade,
        f.ano,
        f.mes,
        f.unidade_canonica,
        f.fator_kg
    FROM staging.fact_precos_mensais f
    ORDER BY
        f.id_produto,
        f.id_localidade,
        f.ano,
        f.mes,
        CASE
            WHEN f.unidade_canonica = 'kg' THEN 0
            WHEN f.fator_kg IS NOT NULL THEN 1
            ELSE 2
        END,
        f.unidade_canonica
)
SELECT
    s.id_produto,
    s.id_localidade,
    s.ano,
    s.mes,
    s.status_cor                                                                 AS status_cor_antigo,
    CASE
        WHEN v.contam_unidade THEN 'AMARELO'
        WHEN v.desvio_efetivo IS NULL THEN 'AMARELO'
        ELSE COALESCE(
            staging.calcular_semaforo_preco_sensivel(
                s.preco_medio, s.media_movel_12m, v.cv_serie, 1
            ),
            'AMARELO'
        )
    END                                                                          AS status_cor_novo,
    v.cv_serie                                                                   AS cv_real,
    v.contam_unidade,
    uf.unidade_canonica                                                          AS unidade_inferida,
    uf.fator_kg,
    s.metadado_transparencia,
    ABS(s.preco_medio - COALESCE(s.media_movel_12m, s.preco_medio))              AS distancia_referencia,
    (UPPER(dp.nome_produto) LIKE '%PITAYA%'
        OR UPPER(dp.nome_produto) LIKE '%BATATA%'
        OR UPPER(dp.nome_produto) LIKE '%ALFACE%')                              AS prioridade_alvo,
    s.status_cor IS DISTINCT FROM
        (CASE
            WHEN v.contam_unidade THEN 'AMARELO'
            WHEN v.desvio_efetivo IS NULL THEN 'AMARELO'
            ELSE COALESCE(
                staging.calcular_semaforo_preco_sensivel(
                    s.preco_medio, s.media_movel_12m, v.cv_serie, 1
                ),
                'AMARELO'
            )
        END)                                                                    AS mudou_status
FROM mart.sazonalidade_produto s
LEFT JOIN staging.dim_produto dp ON dp.id_produto = s.id_produto
LEFT JOIN volatilidade v
    ON v.id_produto = s.id_produto
   AND v.id_localidade = s.id_localidade
LEFT JOIN unidade_fact uf
    ON uf.id_produto = s.id_produto
   AND uf.id_localidade = s.id_localidade
   AND uf.ano = s.ano
   AND uf.mes = s.mes
ORDER BY
    mudou_status DESC,
    prioridade_alvo DESC,
    distancia_referencia DESC
LIMIT 1000;

COMMENT ON VIEW ops.simulacao_semaforo_v82 IS
    'Validation Gate da Migration 82: compara status_cor atual (regra antiga) '
    'com a regra sensível por CV, expõe cv_real/contam_unidade/unidade_inferida '
    'e metadado_transparencia. Prioriza mudanças de status, produtos '
    'PITAYA/BATATA/ALFACE e maiores distâncias |preco_atual - referência|. '
    'LIMIT 1000 linhas mais críticas.';

GRANT SELECT ON ops.simulacao_semaforo_v82 TO role_api_reader, role_etl_writer;

