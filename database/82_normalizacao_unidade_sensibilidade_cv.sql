-- ---------------------------------------------------------------------------
-- 3.1 — staging.estatisticas_volatilidade_24m_cv()
-- ---------------------------------------------------------------------------
-- Evolução de estatisticas_volatilidade_24m() (migrations 65/68):
--  * mesma janela (24m reais), mesmo piso de sanidade (preco >= 0.50),
--    mesmo IQR de Tukey + guard robusto (preco >= 0.25 * mediana) — todos os
--    cálculos sobre preco_por_kg.
--  * NOVO: normaliza a série para preco_por_kg ANTES das estatísticas usando
--    mart.fator_kg_produto_uf (fator por produto+UF) — abordagem C da
--    Migration 53 (preco_medio / fator_kg). Sem fator conhecido, usa o
--    preco cru (mistura de grandezas permanece → contam_unidade = true).
--  * NOVO: cv_serie = desvio_padrao_historico / media_historica e
--    contam_unidade = cv_serie > 0.40 (sinal de série com grandezas mistas).

CREATE OR REPLACE FUNCTION staging.estatisticas_volatilidade_24m_cv()
RETURNS TABLE (
    id_produto              INTEGER,
    id_localidade           INTEGER,
    media_historica         NUMERIC(14,4),
    desvio_padrao_historico NUMERIC(14,4),
    n_meses                 INTEGER,
    cv_serie                NUMERIC(14,4),
    contam_unidade          BOOLEAN,
    desvio_efetivo          NUMERIC(14,4)
)
LANGUAGE sql
STABLE
AS $$
    WITH max_data AS (
        SELECT MAX(ano * 12 + mes) AS max_periodo
        FROM staging.fact_precos_mensais
    ),
    -- Janela bruta: últimos 24 meses reais, piso absoluto de sanidade.
    -- preco_por_kg: normaliza grandezas quando existe fator empírico
    -- (fator_kg_produto_uf) — sem fator, mantém o preco cru (CV alto).
    janela AS (
        SELECT
            f.id_produto,
            f.id_localidade,
            COALESCE(
                f.preco_medio / NULLIF(fk.fator_kg, 0),
                f.preco_medio
            ) AS preco_por_kg
        FROM staging.fact_precos_mensais f
        JOIN staging.dim_localidade l ON l.id_localidade = f.id_localidade
        LEFT JOIN mart.fator_kg_produto_uf fk
            ON fk.id_produto = f.id_produto
           AND fk.uf         = l.uf
        CROSS JOIN max_data m
        WHERE f.ano * 12 + f.mes > m.max_periodo - 24
          AND f.preco_medio >= 0.50
    ),
    quartis AS (
        SELECT
            j.id_produto,
            j.id_localidade,
            PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY j.preco_por_kg) AS q1,
            PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY j.preco_por_kg) AS q3,
            PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY j.preco_por_kg) AS mediana
        FROM janela j
        GROUP BY j.id_produto, j.id_localidade
    ),
    janela_limpa AS (
        SELECT
            j.id_produto,
            j.id_localidade,
            j.preco_por_kg
        FROM janela j
        JOIN quartis q
            ON q.id_produto = j.id_produto
           AND q.id_localidade = j.id_localidade
        WHERE q.q1 IS NOT NULL AND q.q3 IS NOT NULL
          AND j.preco_por_kg BETWEEN (q.q1 - 1.5 * (q.q3 - q.q1))
                                 AND (q.q3 + 1.5 * (q.q3 - q.q1))
          AND (q.mediana IS NULL OR j.preco_por_kg >= 0.25 * q.mediana)
    )
    SELECT
        j.id_produto,
        j.id_localidade,
        AVG(j.preco_por_kg)::NUMERIC(14,4)            AS media_historica,
        STDDEV(j.preco_por_kg)::NUMERIC(14,4)         AS desvio_padrao_historico,
        COUNT(*)::INTEGER                             AS n_meses,
        CASE
            WHEN AVG(j.preco_por_kg) IS NULL OR AVG(j.preco_por_kg) = 0 THEN NULL
            ELSE (STDDEV(j.preco_por_kg) / AVG(j.preco_por_kg))::NUMERIC(14,4)
        END                                           AS cv_serie,
        CASE
            WHEN AVG(j.preco_por_kg) IS NULL OR AVG(j.preco_por_kg) = 0 THEN NULL
            ELSE (STDDEV(j.preco_por_kg) / AVG(j.preco_por_kg)) > 0.40
        END                                           AS contam_unidade,
        CASE
            WHEN AVG(j.preco_por_kg) IS NULL OR AVG(j.preco_por_kg) = 0 THEN NULL
            WHEN STDDEV(j.preco_por_kg) IS NULL
              OR STDDEV(j.preco_por_kg) = 0
              OR (STDDEV(j.preco_por_kg) / AVG(j.preco_por_kg)) < 0.10
                THEN ROUND(0.10 * AVG(j.preco_por_kg), 4)   -- piso CV mínimo 10%
            ELSE STDDEV(j.preco_por_kg)
        END::NUMERIC(14,4)                            AS desvio_efetivo
    FROM janela_limpa j
    GROUP BY j.id_produto, j.id_localidade;
$$;

COMMENT ON FUNCTION staging.estatisticas_volatilidade_24m_cv() IS
    'Estatísticas de volatilidade por (produto, localidade) sobre os últimos '
    '24 meses reais, calculadas sobre preco_por_kg (normalização via '
    'mart.fator_kg_produto_uf — abordagem C da Migration 53). Mesma janela, '
    'piso >= 0.50, IQR de Tukey e guard robusto 0.25*mediana da migration 68. '
    'NOVO: cv_serie = desvio/media e contam_unidade = cv > 0.40 (grandezas '
    'mistas na série). Uso: SELECT * FROM staging.estatisticas_volatilidade_24m_cv();';

GRANT EXECUTE ON FUNCTION staging.estatisticas_volatilidade_24m_cv()
    TO role_etl_writer;

-- ---------------------------------------------------------------------------
-- 3.2 — staging.calcular_semaforo_preco_sensivel(...)
-- ---------------------------------------------------------------------------
-- Semáforo por BANDA PROPORCIONAL ao CV (coeficiente de variação da série):
--   banda = referência * (1 ± cv_efetivo)
-- onde cv_efetivo = GREATEST(COALESCE(cv_serie, 0), piso_da_faixa) e o piso
-- da faixa depende da magnitude do preço de referência:
--   ref <= 5.00         → piso 0.02 (±2%)
--   ref > 5.00 e <=20   → piso 0.05 (±5%)
--   ref > 20.00         → piso 0.08 (±8%)
-- Regras:
--   * qualquer argumento NULL ou <= 0 → NULL (chamador aplica fallback, AMARELO)
--   * cv_efetivo > 0.40 → AMARELO defensivo (série com grandezas mistas:
--     semáforo nunca vibra VERDE/VERMELHO sobre estatística não confiável)
--   * preco < ref*(1-cv_efetivo) → VERDE
--   * preco > ref*(1+cv_efetivo) → VERMELHO
--   * senão → AMARELO
-- p_fator_kg (DEFAULT 1): aplicado sobre preco e referência ANTES da banda,
-- permitindo comparar grandezas diferentes (ex.: preço de caixa vs. ref kg).

CREATE OR REPLACE FUNCTION staging.calcular_semaforo_preco_sensivel(
    p_preco_exibido    NUMERIC,
    p_preco_referencia NUMERIC,
    p_cv_serie         NUMERIC,
    p_fator_kg         NUMERIC DEFAULT 1
)
RETURNS TEXT
LANGUAGE sql
STABLE
AS $$
    WITH cv AS (
        SELECT GREATEST(
            COALESCE(p_cv_serie, 0),
            CASE
                WHEN p_preco_referencia IS NULL OR p_preco_referencia <= 0 THEN 0
                WHEN p_preco_referencia <= 5.00 THEN 0.02
                WHEN p_preco_referencia <= 20.00 THEN 0.05
                ELSE 0.08
            END
        ) AS cv_efetivo
    )
    SELECT CASE
        WHEN p_preco_exibido IS NULL OR p_preco_exibido <= 0 THEN NULL
        WHEN p_preco_referencia IS NULL OR p_preco_referencia <= 0 THEN NULL
        WHEN p_fator_kg IS NULL OR p_fator_kg <= 0 THEN NULL
        WHEN cv.cv_efetivo > 0.40 THEN 'AMARELO'
        WHEN (p_preco_exibido / p_fator_kg)
             < ((p_preco_referencia / p_fator_kg) * (1 - cv.cv_efetivo)) THEN 'VERDE'
        WHEN (p_preco_exibido / p_fator_kg)
             > ((p_preco_referencia / p_fator_kg) * (1 + cv.cv_efetivo)) THEN 'VERMELHO'
        ELSE 'AMARELO'
    END
    FROM cv;
$$;

COMMENT ON FUNCTION staging.calcular_semaforo_preco_sensivel(NUMERIC, NUMERIC, NUMERIC, NUMERIC) IS
    'Semáforo sensível por coeficiente de variação (Migration 82). Banda '
    'proporcional: ref * (1 ± cv_efetivo), com cv_efetivo = GREATEST(cv_serie, '
    'piso_da_faixa) e piso por magnitude (<=5 → 0.02; <=20 → 0.05; >20 → 0.08). '
    'cv_efetivo > 0.40 → AMARELO defensivo (grandezas mistas). p_fator_kg '
    'normaliza preço e referência para comparar grandezas diferentes. '
    'Retorna NULL se qualquer argumento for NULL ou <= 0.';

GRANT EXECUTE ON FUNCTION staging.calcular_semaforo_preco_sensivel(NUMERIC, NUMERIC, NUMERIC, NUMERIC)
    TO role_etl_writer;

-- ---------------------------------------------------------------------------
-- 3.3 — RETROCOMPAT: staging.calcular_semaforo_preco(NUMERIC, NUMERIC, NUMERIC)
-- ---------------------------------------------------------------------------
-- Mantém a assinatura de 3 argumentos (usada por views/SP legadas): deriva o
-- cv a partir do desvio (cv = desvio / referencia, NULL-safe) e delega para a
-- versão sensível. Comportamento equivalente à antiga banda absoluta ±desvio
-- quando o desvio é confiável; ganha os pisos de faixa quando o desvio é baixo.

CREATE OR REPLACE FUNCTION staging.calcular_semaforo_preco(
    p_preco_exibido    NUMERIC,
    p_preco_referencia NUMERIC,
    p_desvio_padrao    NUMERIC
)
RETURNS TEXT
LANGUAGE sql
STABLE
AS $$
    SELECT staging.calcular_semaforo_preco_sensivel(
        p_preco_exibido,
        p_preco_referencia,
        CASE
            WHEN p_preco_referencia IS NULL OR p_preco_referencia = 0 THEN NULL
            WHEN p_desvio_padrao IS NULL THEN NULL
            ELSE p_desvio_padrao / p_preco_referencia
        END,
        1
    );
$$;

COMMENT ON FUNCTION staging.calcular_semaforo_preco(NUMERIC, NUMERIC, NUMERIC) IS
    'RETROCOMPAT da Migration 82: deriva o CV (desvio/referencia, NULL-safe) '
    'e delega para staging.calcular_semaforo_preco_sensivel(). Mantém a '
    'assinatura de 3 argumentos para chamadores legados.';

GRANT EXECUTE ON FUNCTION staging.calcular_semaforo_preco(NUMERIC, NUMERIC, NUMERIC)
    TO role_etl_writer;

-- ============================================================================
-- FASE 4 — Backfill de unidade na fact + mudança do UNIQUE
-- ============================================================================
-- Regra (por (id_produto, uf), mediana em R$/kg de referência):
--   preco_medio >  10 * mediana  → 'cx' (caixa; fator_kg empírico quando
--                                     existir em fator_kg_produto_uf)
--   preco_medio <   0.50         → 'un' (unidade; sem fator confiável)
--   senão                        → 'kg' (fator 1)
-- Fluxo: 'inferido_backfill'. NUNCA sobrescreve unidade_canonica preenchida.

DO $$
DECLARE
    v_total     BIGINT;
    v_kg        BIGINT;
    v_cx        BIGINT;
    v_un        BIGINT;
    v_inicio    TIMESTAMPTZ := clock_timestamp();
    v_fim       TIMESTAMPTZ;
BEGIN
    RAISE NOTICE '[migration_82] Iniciando backfill de unidade na fact...';

    WITH mediana_per_kg AS (
        SELECT
            f.id_produto,
            l.uf,
            COALESCE(
                fk.mediana_preco_medio,
                PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY f.preco_medio)
            ) AS mediana
        FROM staging.fact_precos_mensais f
        JOIN staging.dim_localidade l ON l.id_localidade = f.id_localidade
        LEFT JOIN mart.fator_kg_produto_uf fk
            ON fk.id_produto = f.id_produto
           AND fk.uf         = l.uf
        GROUP BY f.id_produto, l.uf, fk.mediana_preco_medio
    ),
    classificada AS (
        SELECT
            f.id_fato,
            f.id_produto,
            l.uf,
            CASE
                WHEN mp.mediana IS NOT NULL AND f.preco_medio > 10 * mp.mediana THEN 'cx'
                WHEN f.preco_medio < 0.50 THEN 'un'
                ELSE 'kg'
            END AS unidade_canonica,
            CASE
                WHEN mp.mediana IS NOT NULL AND f.preco_medio > 10 * mp.mediana
                    THEN fk2.fator_kg
                WHEN f.preco_medio < 0.50 THEN NULL
                ELSE 1
            END AS fator_kg,
            'inferido_backfill' AS fluxo_unidade
        FROM staging.fact_precos_mensais f
        JOIN staging.dim_localidade l ON l.id_localidade = f.id_localidade
        LEFT JOIN mediana_per_kg mp
            ON mp.id_produto = f.id_produto AND mp.uf = l.uf
        LEFT JOIN mart.fator_kg_produto_uf fk2
            ON fk2.id_produto = f.id_produto AND fk2.uf = l.uf
        WHERE f.unidade_canonica IS NULL
          AND f.preco_medio IS NOT NULL
    )
    UPDATE staging.fact_precos_mensais f
    SET unidade_canonica = c.unidade_canonica,
        fator_kg         = c.fator_kg,
        fluxo_unidade    = c.fluxo_unidade
    FROM classificada c
    WHERE f.id_fato = c.id_fato;

    GET DIAGNOSTICS v_total = ROW_COUNT;

    SELECT COUNT(*) INTO v_kg FROM staging.fact_precos_mensais
        WHERE unidade_canonica = 'kg' AND fluxo_unidade = 'inferido_backfill';
    SELECT COUNT(*) INTO v_cx FROM staging.fact_precos_mensais
        WHERE unidade_canonica = 'cx' AND fluxo_unidade = 'inferido_backfill';
    SELECT COUNT(*) INTO v_un FROM staging.fact_precos_mensais
        WHERE unidade_canonica = 'un' AND fluxo_unidade = 'inferido_backfill';

    v_fim := clock_timestamp();
    RAISE NOTICE '[migration_82] Backfill: % linhas em %s seg | kg=%, cx=%, un=%',
        v_total, ROUND(EXTRACT(EPOCH FROM v_fim - v_inicio)::NUMERIC, 2),
        v_kg, v_cx, v_un;
    RAISE NOTICE '[migration_82] Linhas com unidade_canonica NULL (órfãs): %',
        (SELECT COUNT(*) FROM staging.fact_precos_mensais WHERE unidade_canonica IS NULL);
END $$;

